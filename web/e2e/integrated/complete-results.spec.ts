/** W15B: importadores canonicos + PostgreSQL + API + HTTPS reais. */
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
const python = fileURLToPath(new URL('../../../.venv/bin/python', import.meta.url))
const script = fileURLToPath(new URL('./complete-results-manage.py', import.meta.url))
type Prepared = { cookie_name: string; token: string; projects: string[]; codes: string[]; no_hits_id: string; demo_ids: string[]; repeated_ids: string[] }

test('resultados completos reais preservam unidades, visitas e identidades por projeto', async ({ page, context }) => {
  const prepared: Prepared = JSON.parse(execFileSync(python, [script], { input: '{}', encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }))
  await context.addCookies([{ name: prepared.cookie_name, value: prepared.token, domain: '127.0.0.1', path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }])
  const errorsJS: string[] = []
  page.on('pageerror', error => errorsJS.push(error.name))
  const detailRequests: string[] = []
  page.on('request', request => { if (/\/assessments\/[^/?]+(?:\?|$)/.test(request.url()) && !request.url().includes('/options')) detailRequests.push(request.url()) })
  await page.goto('/equipe')
  await page.getByRole('listbox', { name: 'Projetos da consulta', exact: true }).selectOption(prepared.projects)
  await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
  const table = page.getByRole('table', { name: 'Avaliações filtradas' })
  await expect(table.locator('tbody tr')).toHaveCount(6)
  const instruments = page.getByRole('listbox', { name: 'Instrumento da consulta', exact: true })
  const selected = ['instrumento_sintetico_demo', 'stroop_go_nogo_ptbr']
  await instruments.selectOption(selected)
  await expect(page.getByText('Alterações não aplicadas.', { exact: false })).toBeVisible()
  const search = page.getByRole('searchbox', { name: 'Buscar opções de instrumento da consulta', exact: true })
  await search.fill('SEM_CORRESPONDENCIA')
  await expect(instruments).toHaveValues(selected)
  await search.fill('')
  const queried = page.waitForResponse(response => {
    const url = new URL(response.url())
    return url.pathname.endsWith('/analysis/query') && response.request().postDataJSON().query.filters.test_code?.length === 2
  })
  await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
  expect((await queried).status()).toBe(200)
  await expect(table.locator('tbody tr')).toHaveCount(6)
  await expect(table).toContainText('instrumento_sintetico_demo')
  await expect(table).toContainText('stroop_go_nogo_ptbr')
  await expect(page.getByRole('button', { name: 'Exportar visão filtrada', exact: true })).toBeDisabled()
  // Métricas científicas continuam separadas por instrumento.
  await page.getByRole('listbox', { name: 'Instrumento da consulta', exact: true }).selectOption('stroop_go_nogo_ptbr')
  await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(4)
  for (const label of ['Avaliador', 'Precisão Go (%)', 'Precisão No-Go (%)', 'Omissões', 'Comissões', 'Acertos', 'Rejeições corretas']) {
    await expect(table.getByRole('columnheader', { name: label, exact: true })).toBeVisible()
  }
  expect(await table.evaluate(element => { const parent = element.parentElement!; return parent.scrollWidth > parent.clientWidth })).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await table.screenshot({ path: '/tmp/stroop-w15b-table.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/stroop-w15b-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.evaluate(() => { document.documentElement.style.zoom = '2' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.evaluate(() => { document.documentElement.style.zoom = '' })
  expect(detailRequests).toEqual([]) // tabela e graficos nao disparam detalhe por linha.
  const errors = page.getByRole('table', { name: 'Contagens de erros por projeto' })
  await expect(errors.locator('tbody tr')).toHaveCount(2)
  await expect(errors).toContainText(prepared.codes[0]!)
  await expect(errors).toContainText(prepared.codes[1]!)
  const evolution = page.getByRole('combobox', { name: 'Participante para evolução', exact: true })
  await evolution.selectOption(JSON.stringify([prepared.projects[0], 'P_SINTETICO_W15']))
  const longitudinal = page.getByRole('table', { name: 'Evolução do participante por avaliação' })
  await expect(longitudinal.locator('tbody tr')).toHaveCount(2)
  for (const id of prepared.repeated_ids) await expect(longitudinal).toContainText(id)
  const observedOrder = await longitudinal.locator('tbody tr td:nth-child(5)').allTextContents()
  expect(observedOrder).toEqual([...prepared.repeated_ids].sort())
  await evolution.selectOption(JSON.stringify([prepared.projects[1], 'P_SINTETICO_W15']))
  await expect(longitudinal.locator('tbody tr')).toHaveCount(1)
  await expect(longitudinal).not.toContainText(prepared.repeated_ids[0]!)
  await evolution.selectOption(JSON.stringify([prepared.projects[0], 'P_SINTETICO_SEM_HITS']))
  await expect(longitudinal).toContainText('Ausente')
  await expect(longitudinal).toContainText('50,000')
  await page.getByRole('button', { name: 'Ver avaliação P_SINTETICO_SEM_HITS, visita V_ZERO' }).focus()
  await page.keyboard.press('Enter')
  const detail = page.getByRole('region', { name: 'Detalhe da avaliação' })
  await expect(detail).toBeFocused()
  await expect(detail).toContainText(prepared.no_hits_id)
  await expect(detail).toContainText(prepared.projects[0]!)
  await expect(detail).toContainText('Legado sem identificação técnica')
  await detail.screenshot({ path: '/tmp/stroop-w15b-detail.png' })
  await expect(detail.getByRole('table', { name: 'Tentativas registradas' }).locator('tbody tr')).toHaveCount(16)
  const response = await page.request.get(`/api/v1/projects/${prepared.projects[0]}/assessments/${prepared.no_hits_id}`)
  expect(response.status()).toBe(200)
  const stored = await response.json()
  expect(stored.summary).toMatchObject({ accuracy: 50, accuracy_go_trials: 0, accuracy_no_go_trials: 100,
    total_go_trials: 8, total_no_go_trials: 8, hits: 0, omission_errors: 8, commission_errors: 0, correct_rejections: 8, response_time_seconds: null })
  await expect(page.getByRole('main')).not.toContainText('NOME_SINTETICO_RESTRITO')
  await page.getByRole('button', { name: 'Fechar detalhe', exact: true }).click()
  await page.getByRole('listbox', { name: 'Instrumento da consulta', exact: true }).selectOption('instrumento_sintetico_demo')
  await page.getByRole('button', { name: 'Aplicar filtros', exact: true }).click()
  const generic = page.getByRole('region', { name: 'Resultados por instrumento' })
  await expect(generic.getByRole('heading', { name: 'Demonstração sintética' })).toBeVisible()
  const metrics = generic.getByRole('table', { name: 'Métricas por instrumento e avaliação' })
  await expect(metrics.locator('tbody tr')).toHaveCount(4)
  for (const value of ['2,500', '3,500', '4,000', '8,000', 'count', 'unit']) await expect(metrics).toContainText(value)
  await expect(page.getByText('Precisão média', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Comparações descritivas' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Ver avaliação P_SINTETICO_DEMO, visita V1' }).click()
  await expect(detail).toContainText(prepared.demo_ids[0]!)
  await expect(detail.getByRole('table', { name: 'Tentativas registradas' })).toHaveCount(0)
  await expect(detail.getByRole('button', { name: 'Exportar CSV oficial' })).toHaveCount(0)
  await page.screenshot({ path: '/tmp/stroop-w15b-demo.png', fullPage: true })
  expect(errorsJS).toEqual([])
})
