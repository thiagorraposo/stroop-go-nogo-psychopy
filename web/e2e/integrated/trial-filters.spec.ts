/** QUERY7: filtros de tentativa com React/API/PG/HTTPS reais e fixture sintética. */
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
const python = fileURLToPath(new URL('../../../.venv/bin/python', import.meta.url))
const script = fileURLToPath(new URL('./dashboard-manage.py', import.meta.url))

test('condição e resposta selecionam a mesma tentativa e preservam métricas da avaliação completa', async ({ page, context }) => {
  const prepared = JSON.parse(execFileSync(python, [script], { input: JSON.stringify({ role: 'consulta' }), encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }))
  await context.addCookies([{ name: prepared.cookie_name, value: prepared.token, domain: '127.0.0.1', path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }])
  await page.goto('/equipe')
  const form = page.getByRole('form', { name: 'Filtros da consulta' })
  const table = page.getByRole('table', { name: 'Avaliações filtradas' })
  await expect(table.locator('tbody tr')).toHaveCount(1)
  const card = (label: string) => page.locator('.dashboard-cards > div').filter({ has: page.getByText(label, { exact: true }) }).locator('dd')
  const accuracy = await card('Precisão média').textContent()
  await form.getByText('Filtros avançados e ordenação', { exact: true }).click()
  const condition = form.getByRole('listbox', { name: 'Condição experimental', exact: true })
  const response = form.getByRole('listbox', { name: 'Tipo de resposta / erro', exact: true })
  const apply = form.getByRole('button', { name: 'Aplicar filtros', exact: true })
  await condition.selectOption('congruent')
  await response.selectOption('commission')
  await apply.click()
  await expect(form.getByRole('alert')).toContainText('Selecione somente o instrumento Stroop')
  await form.getByRole('listbox', { name: 'Instrumento da consulta', exact: true }).selectOption('stroop_go_nogo_ptbr')
  const incompatible = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/assessments') && r.url().includes('response_type=commission'))
  await apply.click()
  expect((await incompatible).status()).toBe(200)
  await expect(page.getByText('Nenhuma avaliação corresponde aos filtros.', { exact: true })).toBeVisible()
  await expect(table).toHaveCount(0)
  // All four outcome categories exist, but condition+commission never share a trial.
  await response.selectOption(['hit', 'omission'])
  await apply.focus(); await page.keyboard.press('Enter')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(card('Precisão média')).toHaveText(accuracy!)
  await expect(page.getByText(/^Filtros aplicados:/)).toContainText('respostas: hit, omission')
  await expect(page.getByRole('button', { name: 'Exportar visão filtrada', exact: true })).toBeDisabled()
  await expect(page.getByText('A exportação deste recorte ainda não está disponível.', { exact: false })).toBeVisible()
  await form.getByRole('searchbox', { name: 'Buscar opções de tipo de resposta / erro', exact: true }).fill('comissão')
  await expect(response).toHaveValues(['hit', 'omission'])
  await response.focus(); await page.keyboard.press('ArrowDown')
  expect(await response.evaluate(node => node === document.activeElement)).toBe(true)
  await form.getByRole('button', { name: /^Remover filtro Resposta:/ }).click()
  await expect(form.getByRole('status').filter({ hasText: 'Alterações não aplicadas' })).toBeVisible()
  await form.getByRole('button', { name: 'Descartar alterações', exact: true }).click()
  await expect(response).toHaveValues(['hit', 'omission'])
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(card('Precisão média')).toHaveText(accuracy!)
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  expect(page.url()).not.toContain('response_type')
})
